export function getArticle(slug: string): Article | undefined {
  return ARTICLES.find((a) => a.slug === slug);
}

/** Свежие сверху. */
export const ARTICLES_BY_DATE = [...ARTICLES].sort((a, b) =>
  b.datePublished.localeCompare(a.datePublished),
);

/** Примерное время чтения, минуты. */
export function readingMinutes(article: Article): number {
  const words = article.body.reduce((total, block) => {
    if (block.kind === 'list') return total + block.items.join(' ').split(/\s+/).length;
    return total + block.text.split(/\s+/).length;
  }, article.lead.split(/\s+/).length);
  return Math.max(1, Math.round(words / 150));
}
